package com.openrouter.demo.chat;

import java.time.Instant;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * A character the user can chat with. Maps to the "characters" table from V1__chat.sql.
 *
 * Named ChatCharacter (not Character) so it doesn't clash with java.lang.Character,
 * which every Java file imports automatically.
 */
@Entity
@Table(name = "characters")
public class ChatCharacter {

    // The database generates the id (GENERATED BY DEFAULT AS IDENTITY).
    // IDENTITY tells Hibernate to insert first, then read the new id back.
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // Field names map to columns automatically: exampleDialogue -> example_dialogue.
    // nullable/length mirror the SQL so the Java side documents the same rules.
    @Column(nullable = false, length = 100)
    private String name;

    @Column(nullable = false)
    private String persona;

    private String scenario;

    private String greeting;

    private String exampleDialogue;

    // Set in Java so Hibernate never inserts NULL into a NOT NULL column.
    // updatable = false: once created, this never changes.
    @Column(nullable = false, updatable = false)
    private Instant createdAt = Instant.now();

    // JPA needs a no-argument constructor to build objects from database rows.
    // protected = Hibernate can use it, but your own code is nudged toward the one below.
    protected ChatCharacter() {
    }

    public ChatCharacter(String name, String persona) {
        this.name = name;
        this.persona = persona;
    }

    public Long getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getPersona() {
        return persona;
    }

    public void setPersona(String persona) {
        this.persona = persona;
    }

    public String getScenario() {
        return scenario;
    }

    public void setScenario(String scenario) {
        this.scenario = scenario;
    }

    public String getGreeting() {
        return greeting;
    }

    public void setGreeting(String greeting) {
        this.greeting = greeting;
    }

    public String getExampleDialogue() {
        return exampleDialogue;
    }

    public void setExampleDialogue(String exampleDialogue) {
        this.exampleDialogue = exampleDialogue;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }
}
